u32 load_le32(const u8* p)
{
    return (u32)p[0] | (u32)p[1] << 8 | (u32)p[2] << 16 | (u32)p[3] << 24;
}

u64 load_le64(const u8* p)
{
    return load_le32(p) | (u64)load_le32(p + 4) << 32;
}

void quarter_round(u32 (&x)[16], u32 a, u32 b, u32 c, u32 d)
{
    x[a] += x[b];
    x[d] = std::rotl(x[d] ^ x[a], 16);
    x[c] += x[d];
    x[b] = std::rotl(x[b] ^ x[c], 12);
    x[a] += x[b];
    x[d] = std::rotl(x[d] ^ x[a], 8);
    x[c] += x[d];
    x[b] = std::rotl(x[b] ^ x[c], 7);
}

