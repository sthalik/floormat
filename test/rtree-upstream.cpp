void test_tree_list()
{
    using Tree = ::RTree<int, int, 2, float, 4>;
    Tree t;
    for (int i = 0; i < 10; i++)
    {
        const int p[2] = {i, i};
        t.Insert(p, p, i);
    }
    Array<Tree::Rect> rects;
    Array<Tree::Node*> nodes;
    t.ListTree(rects, nodes);
    fm_assert(rects.size() > 10);
}

