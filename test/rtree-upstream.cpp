struct box2i { int min[2], max[2]; int value; };

constexpr box2i basic_boxes[] = {
    { {0, 0}, {2, 2}, 0 },
    { {5, 5}, {7, 7}, 2 },
    { {8, 5}, {9, 6}, 3 },
    { {7, 1}, {9, 2}, 5 },
};

template<typename Tree>
void check_basic_entries(Tree& t)
{
    u32 seen = 0, n = 0;
    typename Tree::Iterator it;
    for (t.GetFirst(it); !t.IsNull(it); t.GetNext(it))
    {
        const int value = t.GetAt(it);
        int lo[2], hi[2];
        it.GetBounds(lo, hi);
        const box2i* b = nullptr;
        for (const auto& x : basic_boxes)
            if (x.value == value)
                b = &x;
        fm_assert(b);
        fm_assert(lo[0] == b->min[0] && lo[1] == b->min[1] && hi[0] == b->max[0] && hi[1] == b->max[1]);
        fm_assert(!(seen & 1u << value));
        seen |= 1u << value;
        n++;
    }
    fm_assert_equal(4u, n);

    n = 0;
    for (t.GetFirst(it); !it.IsNull(); ++it)
    {
        fm_assert(seen & 1u << *it);
        n++;
    }
    fm_assert_equal(4u, n);
}

void test_basics()
{
    using Tree = ::RTree<int, int, 2, float>;
    Tree t;
    for (const auto& b : basic_boxes)
        t.Insert(b.min, b.max, b.value);

    const int lo[2] = {6, 4}, hi[2] = {10, 6};
    u32 mask = 0;
    const int hits = t.Search(lo, hi, [&](int value, const Tree::Rect&) {
        mask |= 1u << value;
        return true;
    });
    fm_assert_equal(2, hits);
    fm_assert_equal((1u << 2) | (1u << 3), mask);

    check_basic_entries(t);
    Tree copy = t;
    check_basic_entries(copy);
}

void test_memory()
{
    using Tree = ::RTree<int, float, 3>;
    struct thing { float min[3], max[3]; bool live; };
    constexpr u32 count = 40, step = 4;

    Random::xoshiro256starstar rng;
    Random::seed(rng, 1);
    const auto rnd = [&](float lo, float hi) { return lo + (hi - lo) * float(Random::next(rng) % 65536) / 65536; };
    thing things[count + count / step];
    Tree t;
    const auto add = [&](u32 i) {
        auto& x = things[i];
        for (u32 k = 0; k < 3; k++)
        {
            x.min[k] = rnd(-10, 10);
            x.max[k] = x.min[k] + rnd(0, 5);
        }
        x.live = true;
        t.Insert(x.min, x.max, int(i));
    };

    for (u32 i = 0; i < count; i++)
        add(i);
    fm_assert_equal(int(count), t.Count());
    for (u32 i = 0; i < count; i += step)
    {
        t.Remove(things[i].min, things[i].max, int(i));
        things[i].live = false;
    }
    fm_assert_equal(int(count - count / step), t.Count());
    for (u32 i = count; i < count + count / step; i++)
        add(i);
    fm_assert_equal(int(count), t.Count());

    const float lo[3] = {-10, -10, -10}, hi[3] = {10, 10, 10};
    u64 found = 0;
    const int hits = t.Search(lo, hi, [&](int id, const Tree::Rect&) {
        fm_assert(things[id].live && !(found & u64{1} << id));
        found |= u64{1} << id;
        return true;
    });
    fm_assert_equal(int(count), hits);

    u64 listed = 0;
    Tree::Iterator it;
    for (t.GetFirst(it); !t.IsNull(it); t.GetNext(it))
        listed |= u64{1} << t.GetAt(it);
    fm_assert_equal(found, listed);

    t.RemoveAll();
    fm_assert_equal(0, t.Count());
}

